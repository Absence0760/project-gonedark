//! **Offline** regeneration tool for the fixed-point trig lookup tables — NOT a build
//! script (D108).
//!
//! The tables the sim reads live as **checked-in integer source** in
//! `core/src/lut_data.rs`, hash-locked by `core::trig`'s `lut_table_hash_is_locked`
//! test. This generator is retained per the repo's committed-generator convention (the
//! same pattern as `tools/fonts/gen_hud_font.py` et al.): the script that produced the
//! data stays in the tree, documented and re-runnable, but its output is committed.
//!
//! Why it is no longer a build script (D108, superseding the D17-era "the build script
//! may use host `f64`" pattern): this tool uses the host's `f64::sin()`/`f64::atan()`,
//! and host libm is **not** bit-identical across platforms/libc versions — two build
//! hosts could bake *different* constant tables into their binaries, a silent lockstep
//! divergence the CI checksum matrix can't fully prove away for the cargo-ndk Android
//! packaging pipeline. Checking the table in removes host libm from the trust chain:
//! every build of every target compiles the identical committed integers.
//!
//! Regenerate (only if the table *shape* is deliberately changed — a data diff on an
//! unchanged shape means your host libm disagrees with the committed table; keep the
//! committed bytes, they are the recorded-checksum baseline):
//!
//! ```text
//! rustc --edition 2021 core/build/lut.rs -o /tmp/gen_lut
//! /tmp/gen_lut > core/src/lut_data.rs
//! ```
//!
//! Then update the locked hash constant in `core/src/trig.rs` and record the change as
//! a new decision — the table is lockstep-affecting data.

/// Q16.16 scale. Must match `core::fixed::Fixed::FRAC_BITS`.
const FRAC_BITS: u32 = 16;
const SCALE: f64 = (1u64 << FRAC_BITS) as f64; // noqa: float-in-sim — host build script; bakes integer bits, never runs in sim

/// Entries in the sine table over one full turn. A power of two so angle wrapping is a
/// mask. 4096 keeps the per-step error tiny before the (fixed-point) linear interp.
const SIN_LUT_LEN: usize = 4096;

/// Bits of angle resolution — must match `core::trig::ANGLE_BITS`. A full turn is
/// `1 << ANGLE_BITS` angle-units, so the atan table below emits results in those units.
const ANGLE_BITS: u32 = 16;
const ANGLE_FULL: f64 = (1u32 << ANGLE_BITS) as f64; // noqa: float-in-sim — host build script

/// Entries in the arctangent table, sampling `atan(t)` for `t` in `[0, 1]`. Indexed by the
/// fixed-point ratio `min(|x|,|y|) / max(|x|,|y|)` during octant-reduced `atan2`. 1024 gives
/// well under one angle-unit of error across the first octant after the integer ratio index.
const ATAN_LUT_LEN: usize = 1024;

fn main() {
    let mut src = String::new();
    src.push_str("// @generated by build/lut.rs — do not edit.\n");
    src.push_str(&format!("pub const SIN_LUT_LEN: usize = {SIN_LUT_LEN};\n"));
    src.push_str(&format!("pub static SIN_LUT: [i32; {SIN_LUT_LEN}] = [\n"));
    for i in 0..SIN_LUT_LEN {
        let theta = (i as f64) / (SIN_LUT_LEN as f64) * std::f64::consts::TAU; // noqa: float-in-sim noqa: transcendental-in-sim — compile-time host math; emits integer LUT
        let bits = (theta.sin() * SCALE).round() as i32; // noqa: transcendental-in-sim — host build script bakes the LUT the sim then reads (invariant #1 pattern)
        src.push_str(&format!("    {bits},\n"));
    }
    src.push_str("];\n");

    // Arctangent table in angle-units: ATAN_LUT[i] = atan(i/(LEN-1)) for the first octant
    // (result in [0, ANGLE_FULL/8]). `atan2` reduces any vector to this octant by sign/swap,
    // indexes by the fixed-point ratio of the smaller to the larger component, and reflects the
    // base angle into the right quadrant — all integer ops in the sim (invariant #1).
    src.push_str(&format!("pub const ATAN_LUT_LEN: usize = {ATAN_LUT_LEN};\n"));
    src.push_str(&format!("pub static ATAN_LUT: [i32; {ATAN_LUT_LEN}] = [\n"));
    for i in 0..ATAN_LUT_LEN {
        let t = (i as f64) / ((ATAN_LUT_LEN - 1) as f64); // noqa: float-in-sim — host build script
        // atan(t) in radians → turns (÷ TAU) → angle-units (× ANGLE_FULL).
        let units = (t.atan() / std::f64::consts::TAU * ANGLE_FULL).round() as i32; // noqa: float-in-sim noqa: transcendental-in-sim — host build script bakes the LUT the sim reads (invariant #1 pattern)
        src.push_str(&format!("    {units},\n"));
    }
    src.push_str("];\n");

    // Emit to stdout; the caller redirects into core/src/lut_data.rs (see module doc).
    print!("{src}");
}
